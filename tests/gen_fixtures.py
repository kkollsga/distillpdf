def gen_glyph_run_labels():
    """A figure whose labels are drawn ONE GLYPH PER ``Tj`` — the shape a cartographic
    exporter emits, and the shape that made a decoded label unreadable.

    ``geology_usgs_fs.pdf`` p1 draws its map's place names a glyph at a time. Every glyph was
    claimed by the figure, mapped into its local space and emitted — as ten ``<text>``
    elements reading ``C`` ``l`` ``o`` ``v`` ``e`` ``r`` ``d`` ``a`` ``l`` ``e``. The map
    LOOKED right, but the word did not exist in the output: not searchable, not selectable,
    invisible to any token-level check. (It was filed as "decoded but never rendered"; it was
    in fact never *assembled* — the body path assembles spans into runs, the figure-label
    path never did.)

    One page, one uncaptioned map figure (Béziers, so the ink gate keeps it), carrying:

      * ``Cloverdale`` — one ``Tj`` per glyph at natural advances. Must come back as ONE
        ``<text>``; this is the defect.
      * ``Healdsburg`` — the same word length drawn as a single ``Tj``. The control: joining
        must not disturb a label that was already whole.
      * ``Santa Rosa`` — glyph by glyph, with the word space drawn as a real GAP (no space
        glyph). Must stay TWO elements: the join closes gaps the reader cannot see, and never
        invents a space.
      * ``Sonoma`` — one ``Tj`` at 90 deg. A rotated label must come through the join pass
        untouched. (The rotated *glyph run* — adjacency measured along the baseline rather
        than along x — is pinned in `vector::tests` instead: the TEXT pillar does not assemble
        a rotated glyph run either, so an end-to-end fixture for it could not also carry the
        "every extracted word is rendered" invariant this file asserts.)
      * ``Napa`` — on ``Cloverdale``'s baseline but far to the right. A shared baseline is not
        a shared word.
    """
    from reportlab.pdfbase.pdfmetrics import stringWidth
    pdf = os.path.join(OUT, "glyph_run_labels.pdf")
    c = canvas.Canvas(pdf, pagesize=letter)
    FONT, SZ = "Helvetica", 7.5

    def glyphs(x, y, s):
        """Draw `s` one `Tj` per glyph at its natural advances; a space becomes a real gap."""
        for ch in s:
            if ch != " ":
                c.drawString(x, y, ch)
            x += stringWidth(ch, FONT, SZ)

    mx, my, mw, mh = float(LM), 300.0, 400.0, 400.0
    c.setStrokeColorRGB(0.1, 0.3, 0.6)
    c.setLineWidth(0.9)
    for k in range(6):  # a curved coastline: graphic ink no ruled table can draw
        off = k * 12.0
        pth = c.beginPath()
        pth.moveTo(mx + 20 + off, my + 30)
        pth.curveTo(mx + 90 + off, my + 140, mx + 40 + off, my + 250, mx + 130 + off, mh + my - 40)
        c.drawPath(pth, stroke=1, fill=0)
    for k in range(6):
        c.line(mx + 200, my + 40 + k * 55, mx + 380, my + 90 + k * 55)
    c.setStrokeColorRGB(0, 0, 0)
    c.setFont(FONT, SZ)
    glyphs(mx + 30, my + 320, "Cloverdale")
    glyphs(mx + 220, my + 320, "Napa")
    c.drawString(mx + 30, my + 280, "Healdsburg")
    glyphs(mx + 30, my + 240, "Santa Rosa")
    c.saveState()
    c.translate(mx + 300, my + 120)
    c.rotate(90)
    c.drawString(0, 0, "Sonoma")
    c.restoreState()
    c.setFont(BODY_F, BODY_S)
    c.drawString(LM, my - 40, "The map above is uncaptioned; its place names are its own labels.")
    c.showPage()
    c.save()
    GT["glyph_run_labels.pdf"] = {
        "joined": ["Cloverdale", "Sonoma"],
        "whole_already": ["Healdsburg"],
        "must_stay_apart": ["Santa", "Rosa", "Napa"],
    }


def gen_ink_gate():
    """The three cases the figure-ink gate has to tell apart, all rects-only.

    None of these pages draws a curve or a slanted line, so `has_graphic_ink` says no to all
    three and the gate's verdict rests entirely on the palette:

    * page 1 — a **column chart**: bars in four saturated series colours. It is a real
      figure and must be accepted (this is the shape of the Excel charts on
      `Kaspersen_MScThesis` p131/p132, whose `#4a7ebb #98b954 #be4b48` survive the gate).
    * page 2 — a **shaded data table**: the same rectangles, but the only fills are a grey
      header band and zebra row shading. Page furniture; must be demoted.
    * page 3 — an **invisible white-rect layer** over prose: a stack of white rectangles
      painted on a white page, drawing nothing a reader can see. Must be demoted.

    Neither page 2 nor page 3 carries a figure caption, so a demotion is the end of the road
    for them — which is exactly what the assertion checks. Page 4 repeats page 2's table on a
    ``/Rotate 90`` page, where the gate stands down (the body pipeline drops rotated spans, so
    the figure is the page's only text carrier).
    """
    pdf = os.path.join(OUT, "ink_gate.pdf")
    c = canvas.Canvas(pdf, pagesize=letter)

    # ---- page 1: a column chart, rects only, four series colours.
    series = [(0.29, 0.49, 0.73), (0.60, 0.73, 0.33), (0.75, 0.29, 0.28), (0.49, 0.38, 0.63)]
    bx, by, bw = float(LM), 480.0, 96.0
    for g in range(4):
        for s, col in enumerate(series):
            c.setFillColorRGB(*col)
            h = 30.0 + 18.0 * ((g + s) % 4)
            c.rect(bx + g * bw + s * 20.0, by, 18.0, h, stroke=0, fill=1)
    c.setStrokeColorRGB(0, 0, 0)
    c.setLineWidth(0.8)
    c.line(bx, by, bx + 4 * bw, by)  # axis
    c.line(bx, by, bx, by + 130.0)
    c.setFillColorRGB(0, 0, 0)
    c.setFont("Helvetica", 8)
    for g in range(4):
        c.drawString(bx + g * bw + 24.0, by - 12.0, f"Q{g + 1}")
    c.showPage()

    # ---- page 2: a shaded data table. Grey header + zebra rows + rules. No palette.
    tx, ty, tw, rh = float(LM), 520.0, 400.0, 22.0
    c.setFillColorRGB(0.85, 0.85, 0.85)
    c.rect(tx, ty, tw, rh, stroke=0, fill=1)
    for r in range(1, 7):
        c.setFillColorRGB(0.95, 0.95, 0.95) if r % 2 else c.setFillColorRGB(1, 1, 1)
        c.rect(tx, ty - r * rh, tw, rh, stroke=0, fill=1)
    c.setStrokeColorRGB(0, 0, 0)
    c.setLineWidth(0.6)
    for r in range(8):
        c.line(tx, ty + rh - r * rh, tx + tw, ty + rh - r * rh)
    for k in range(5):
        c.line(tx + k * (tw / 4), ty + rh, tx + k * (tw / 4), ty - 6 * rh)
    c.setFillColorRGB(0, 0, 0)
    c.setFont("Helvetica", 8)
    for r in range(7):
        for k in range(4):
            c.drawString(tx + k * (tw / 4) + 6, ty + 6 - r * rh, f"{r}.{k}")
    c.showPage()

    # ---- page 3: an invisible white-rect layer over prose.
    c.setFont("Helvetica", 10)
    for i in range(12):
        c.drawString(LM, 700.0 - i * 14.0, "Body prose that the invisible layer sits on top of, line %d." % (i + 1))
    c.setFillColorRGB(1, 1, 1)
    for i in range(10):
        c.rect(float(LM), 690.0 - i * 14.0, 400.0, 10.0, stroke=0, fill=1)
    c.showPage()

    # ---- page 4: page 2's shaded table again, on a /Rotate 90 page. It must be ACCEPTED.
    # `layout::lines_of` drops rotated spans from the body reading order, so on a quarter-
    # turned page the figure is the only thing carrying the page's text into the output and
    # the gate stands down (see `vector::cluster_figures`). Byte-identical ink to page 2, so
    # the turn is the only difference between the two verdicts.
    c.setPageRotation(90)
    c.setFillColorRGB(0.85, 0.85, 0.85)
    c.rect(tx, ty, tw, rh, stroke=0, fill=1)
    for r in range(1, 7):
        c.setFillColorRGB(0.95, 0.95, 0.95) if r % 2 else c.setFillColorRGB(1, 1, 1)
        c.rect(tx, ty - r * rh, tw, rh, stroke=0, fill=1)
    c.setStrokeColorRGB(0, 0, 0)
    c.setLineWidth(0.6)
    for r in range(8):
        c.line(tx, ty + rh - r * rh, tx + tw, ty + rh - r * rh)
    for k in range(5):
        c.line(tx + k * (tw / 4), ty + rh, tx + k * (tw / 4), ty - 6 * rh)
    c.setFillColorRGB(0, 0, 0)
    c.setFont("Helvetica", 8)
    for r in range(7):
        for k in range(4):
            c.drawString(tx + k * (tw / 4) + 6, ty + 6 - r * rh, f"{r}.{k}")
    c.showPage()
    c.save()
    GT["ink_gate.pdf"] = {"page1_figures": 1, "page2_figures": 0, "page3_figures": 0, "page4_figures": 1}


