def gen_glyph_table():
    """A data table whose body is drawn one ``Tj`` per glyph — the SEC-filing idiom.

    Spans are word-level *at best*: a generator is entitled to emit one show-operator per
    glyph, and every SEC filing in the local corpus does. Every path that concatenates spans
    has to decide whether a space belongs between two of them, and the table-cell builders
    did not decide at all — they spaced **every** appended span. ``Texas`` therefore came out
    of a ``<th>`` as ``T e x a s``, in 266 of the corpus's 632 detected tables, and any
    signal that reads cell TEXT (word counts, prose detection, a table-quality judgement)
    was reading shredded input.

    Courier is monospace, so every advance here is exactly ``0.6 x 9 pt = 5.4``: a glyph
    boundary is a gap of 0 and a real word space is a gap of 5.4 (0.6 em). Both sides of the
    rule are therefore pinned by one fixture:

      row 0  drawn as whole words   -> the control: unchanged behaviour
      rows 1-3 drawn glyph by glyph -> must read as words, not as spaced letters
      ``East ridge``                -> a real space INSIDE a glyph-drawn cell must survive
      ``42.5``                      -> and a decimal point must not become ``42 . 5``"""
    pdf = os.path.join(OUT, "glyph_table.pdf")
    ADV = 5.4  # Courier at 9 pt
    COLS = (72.0, 220.0, 360.0)
    ROWS = [
        ["Region", "Samples", "Depth"],
        ["North", "128", "42.5"],
        ["South", "96", "31.0"],
        ["East ridge", "77", "18.2"],
    ]

    def whole(x, y, s):
        return b"BT /F1 9 Tf %.2f %.2f Td (%s) Tj ET" % (x, y, s.encode())

    def per_glyph(x, y, s):
        out = []
        for i, ch in enumerate(s):
            if ch != " ":
                out.append(b"BT /F1 9 Tf %.2f %.2f Td (%s) Tj ET" % (x + i * ADV, y, ch.encode()))
        return b"\n".join(out)

    body = [b"BT /F2 15 Tf 72 740 Td (A Table Drawn One Glyph At A Time) Tj ET"]
    for ri, row in enumerate(ROWS):
        y = 700.0 - ri * 16.0
        for ci, cell in enumerate(row):
            body.append((whole if ri == 0 else per_glyph)(COLS[ci], y, cell))
    stream = b"\n".join(body)
    objs = {
        1: b"<< /Type /Catalog /Pages 2 0 R >>",
        2: b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        3: (b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << "
            b"/Font << /F1 5 0 R /F2 6 0 R >> >> /Contents 4 0 R >>"),
        4: b"<< /Length %d >>\nstream\n%s\nendstream" % (len(stream), stream),
        5: b"<< /Type /Font /Subtype /Type1 /BaseFont /Courier /Encoding /WinAnsiEncoding >>",
        6: b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>",
    }
    _assemble_pdf(objs, pdf)
    GT["glyph_table.pdf"] = {"cells": ROWS}


def gen_tagged_table():
    """A **tagged** PDF: one page that declares its table structure in ``/StructTreeRoot``.

    This is the L0 fixture — accept, reject and mask-not-switch in one file. Everything a
    declared table can say is said here, and every one of the three outcomes is asserted:

      * **Accepted** — ``Table 1`` is declared 3x3 with a header row whose first ``/TH``
        carries ``/ColSpan 2``, and a first data cell carrying ``/RowSpan 2``. Its emitted
        grid must be exactly what the declaration says (3 ``<tr>``, 3 columns, the spanning
        cell's text in its first covered position), not what alignment inference would guess.
        One of its cells names its marked content **indirectly** (``/K [N 0 R]`` where object
        N is the integer) — legal, and the shape every World Bank document in the measurement
        corpus uses; reading only DIRECT integers found the declaration and none of its
        content, so the whole table was (correctly, uselessly) refused by the trust rule.
      * **Refused** — two degenerate declarations that a tagged file is entitled to contain:
        a single-row shard (``/Table`` with one ``/TR``) and a single-column one (three
        ``/TR``s of one ``/TD``). Neither is a table whatever the file says, and both must
        fall through to inference rather than be emitted.
      * **Not switched** — an UNDECLARED ruled table lower on the same page, outside every
        declared region and named by no structure element. Inference must still find it, at
        its own row/column count. This is the guarantee that L0 masks its region rather than
        taking over the page: partial coverage is the norm (IRS f1040 p1 declares one of its
        two tables), so a page must be able to carry both kinds at once.

    Hand-assembled: reportlab writes no structure tree."""
    pdf = os.path.join(OUT, "tagged_table.pdf")
    # --- the declared table (marked content, one MCID per cell) --------------------------
    DECL = [
        # (mcid, x, y, text) — row 0 header, rows 1-2 data
        (0, 72, 700, "Region"), (1, 300, 700, "Total"),
        (2, 72, 682, "North"), (3, 186, 682, "Alpha"), (4, 300, 682, "11"),
        (5, 186, 664, "Beta"), (6, 300, 664, "22"),
    ]
    SHARD_ROW = [(7, 72, 600, "one"), (8, 186, 600, "row"), (9, 300, 600, "only")]
    SHARD_COL = [(10, 72, 560, "alpha"), (11, 72, 542, "beta"), (12, 72, 524, "gamma")]
    # --- the undeclared ruled table (no marked content at all) --------------------------
    PLAIN = [["Site", "Depth", "Yield"], ["Ridge", "18.2", "77"],
             ["Basin", "31.0", "96"], ["Delta", "42.5", "128"]]
    PLAIN_X = (72.0, 220.0, 360.0)
    PLAIN_TOP = 430.0

    def marked(mcid, x, y, s, size=10):
        return (b"/P << /MCID %d >> BDC BT /F1 %d Tf %.1f %.1f Td (%s) Tj ET EMC"
                % (mcid, size, x, y, s.encode()))

    body = [b"BT /F2 15 Tf 72 740 Td (A Table The File Declares) Tj ET"]
    for m, x, y, s in DECL + SHARD_ROW + SHARD_COL:
        body.append(marked(m, x, y, s))
    body.append(b"BT /F1 10 Tf 72 470 Td "
                b"(The grid below is drawn and ruled but named by no structure element.) Tj ET")
    for ri, row in enumerate(PLAIN):
        y = PLAIN_TOP - ri * 18.0
        for ci, cell in enumerate(row):
            body.append(b"BT /F1 10 Tf %.1f %.1f Td (%s) Tj ET" % (PLAIN_X[ci], y, cell.encode()))
    for ri in range(len(PLAIN) + 1):  # horizontal rules around every row
        y = PLAIN_TOP + 12.0 - ri * 18.0
        body.append(b"0.6 w 60 %.1f m 460 %.1f l S" % (y, y))
    stream = b"\n".join(body)

    def elem(s, kids, extra=b""):
        return b"<< /Type /StructElem /S /%s /Pg 3 0 R %s/K [%s] >>" % (s, extra, kids)

    def cell(tag, mcids, span=b""):
        a = b"/A << /O /Table %s >> " % span if span else b""
        return elem(tag, b" ".join(mcids), a)

    objs = {
        1: b"<< /Type /Catalog /Pages 2 0 R /StructTreeRoot 7 0 R /MarkInfo << /Marked true >> >>",
        2: b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        3: (b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /StructParents 0 "
            b"/Resources << /Font << /F1 5 0 R /F2 6 0 R >> >> /Contents 4 0 R >>"),
        4: b"<< /Length %d >>\nstream\n%s\nendstream" % (len(stream), stream),
        5: b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>",
        6: b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>",
        7: b"<< /Type /StructTreeRoot /K [8 0 R] >>",
        8: elem(b"Document", b"9 0 R 13 0 R 17 0 R"),
        # Table 1 — accepted. Header /TH with /ColSpan 2, first data /TD with /RowSpan 2.
        9: elem(b"Table", b"10 0 R 11 0 R 12 0 R"),
        10: elem(b"TR", b"%s %s" % (cell(b"TH", [b"0"], b"/ColSpan 2"), cell(b"TH", [b"1"]))),
        11: elem(b"TR", b"%s %s %s" % (cell(b"TD", [b"2"], b"/RowSpan 2"),
                                       cell(b"TD", [b"21 0 R"]),  # INDIRECT MCID (obj 21 = 3)
                                       cell(b"TD", [b"4"]))),
        12: elem(b"TR", b"%s %s" % (cell(b"TD", [b"5"]), cell(b"TD", [b"6"]))),
        # Table 2 — one row: refused (TooFewRows).
        13: elem(b"Table", b"14 0 R"),
        14: elem(b"TR", b"%s %s %s" % (cell(b"TD", [b"7"]), cell(b"TD", [b"8"]), cell(b"TD", [b"9"]))),
        # Table 3 — one column: refused (TooFewCols).
        17: elem(b"Table", b"18 0 R 19 0 R 20 0 R"),
        18: elem(b"TR", cell(b"TD", [b"10"])),
        19: elem(b"TR", cell(b"TD", [b"11"])),
        20: elem(b"TR", cell(b"TD", [b"12"])),
        21: b"3",
    }
    for n in (15, 16):  # keep the object numbers contiguous for the xref writer
        objs[n] = b"<< >>"
    _assemble_pdf(objs, pdf)
    GT["tagged_table.pdf"] = {
        "declared_grid": [["Region", "", "Total"], ["North", "Alpha", "11"], ["", "Beta", "22"]],
        "declared_rows": 3,
        "declared_cols": 3,
        "refused": ["single-row shard", "single-column shard"],
        "undeclared_rows": PLAIN,
    }


def gen_annot_render():
    """A `/Stamp` whose appearance draws a raster, vector ink AND text at a `/BBox` that has
    to be SCALED — non-uniformly — to reach its `/Rect`.

    PDF 32000-1 §12.5.5: an annotation's normal appearance is a Form XObject a viewer paints
    onto the page, reached from neither the content stream nor the page's `/Resources`. The
    render path ignored `/Annots` entirely, because placing one is not a rewire: the
    appearance algorithm maps the `/Matrix`-transformed `/BBox` onto `/Rect`, and nothing in
    the crate computed that. A corpus stamp carries `/BBox [0 0 13.9 17.4]` against `/Rect
    [344.9 456.1 348.9 461.1]` — drawn at its own coordinates its image lands ~345 pt adrift.

    The mapping is pinned by making every factor different and none of them 1:

      /Matrix [2 0 0 2 0 0]  x  /BBox [0 0 50 50]  ->  A = (0, 0, 100, 100)
      /Rect [200 400 400 550]  ->  sx = 2, sy = 1.5   (NON-uniform: sx != sy)
      total: x scales x4 and y scales x3 off an origin at (200, 400)

    so form point (2, 2) lands at (208, 406) and form point (2, 40) at (208, 520). Nothing
    but the full algorithm puts them there.

    The other three annotations are the selection rules a RENDERER must apply, each carrying
    a word that must never reach the output:
      * a hidden `/Stamp` (`/F 2`) — §12.5.3 says do not display and do not print;
      * a `/Widget` whose `/AS /On` selects one of two states — the other must not paint;
      * a `/Widget` with a state dictionary and NO `/AS` — no state is current, so a renderer
        draws nothing. (`extract_images`'s *collector* takes every state instead; the two
        readings are deliberately different and `walker::StateRule` names both.)"""
    pdf = os.path.join(OUT, "annot_render.pdf")
    img = _flate_image(5, 2, 2, b"/DeviceRGB", 8,
                       bytes((220, 30, 40, 30, 160, 60, 40, 60, 210, 230, 190, 40)))

    # The stamp's appearance, in FORM space (0..50 square, before /Matrix doubles it).
    stamp_ap = b"\n".join([
        b"q 0.20 0.60 0.60 rg 0 0 50 50 re f Q",                      # panel
        b"q 0 0 0 RG 0.4 w 0 0 50 50 re S Q",                         # frame
        b"q 0 0 0 RG 0.4 w 2 2 m 48 48 l S Q",                        # a slanted line: graphic ink
        b"q 0 0 0 RG 0.4 w 48 2 m 2 48 l S Q",
        # the same three-swatch palette every owned figure fixture carries (see
        # `gen_clipped_raster`) so the ink gate judges this a figure, not a ruled box
        b"q 0.85 0.20 0.15 rg 3 44 3 3 re f Q",
        b"q 0.20 0.55 0.80 rg 8 44 3 3 re f Q",
        b"q 0.95 0.75 0.10 rg 13 44 3 3 re f Q",
        b"q 10 0 0 10 2 2 cm /ImAp Do Q",                             # -> (208, 406) 40x30
        b"BT /F1 4 Tf 2 40 Td (StampInkVisible) Tj ET",               # -> (208, 520) size 12
    ])

    def text_ap(word):
        return b"BT /F1 10 Tf 2 4 Td (%s) Tj ET" % word

    def form(num, res, content, bbox=b"[0 0 50 50]", matrix=b""):
        return (b"<< /Type /XObject /Subtype /Form /FormType 1 /BBox %s %s"
                b"/Resources %s /Length %d >>\nstream\n%s\nendstream"
                % (bbox, matrix, res, len(content), content))

    page_content = (
        b"BT /F1 19 Tf 72 720 Td (Annotation Appearances Are Page Content) Tj ET\n"
        b"BT /F1 10 Tf 72 700 Td (The panel below is drawn by a /Stamp annotation.) Tj ET"
    )
    font = b"<< /Font << /F1 6 0 R >> >>"
    objs = {
        1: b"<< /Type /Catalog /Pages 2 0 R >>",
        2: b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        3: (b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << "
            b"/Font << /F1 6 0 R >> >> /Contents 4 0 R "
            b"/Annots [8 0 R 10 0 R 14 0 R 18 0 R] >>"),
        4: b"<< /Length %d >>\nstream\n%s\nendstream" % (len(page_content), page_content),
        5: img,
        6: b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>",
        # 1. the /Stamp whose appearance must land at (200,400)-(400,550), scaled 4x by 3x
        7: form(7, b"<< /Font << /F1 6 0 R >> /XObject << /ImAp 5 0 R >> >>", stamp_ap,
                matrix=b"/Matrix [2 0 0 2 0 0] "),
        8: b"<< /Type /Annot /Subtype /Stamp /Rect [200 400 400 550] /F 4 /AP << /N 7 0 R >> >>",
        # 2. HIDDEN (/F bit 2): a viewer neither displays nor prints it
        9: form(9, font, text_ap(b"HiddenStampMustNotPaint")),
        10: b"<< /Type /Annot /Subtype /Stamp /Rect [72 300 300 340] /F 2 /AP << /N 9 0 R >> >>",
        # 3. /AS selects exactly one state
        11: form(11, font, text_ap(b"SelectedStateOn")),
        12: form(12, font, text_ap(b"UnselectedStateOff")),
        14: (b"<< /Type /Annot /Subtype /Widget /Rect [72 250 300 290] /F 4 /AS /On "
             b"/AP << /N << /On 11 0 R /Off 12 0 R >> >> >>"),
        # 4. a state dictionary with NO /AS: no state is current, so a RENDERER paints nothing
        15: form(15, font, text_ap(b"NoStateSelected")),
        18: (b"<< /Type /Annot /Subtype /Widget /Rect [72 200 300 240] /F 4 "
             b"/AP << /N << /S1 15 0 R >> >> >>"),
        # /_assemble_pdf needs contiguous object numbers.
        13: b"<< /Type /Null >>",
        16: b"<< /Type /Null >>",
        17: b"<< /Type /Null >>",
    }
    _assemble_pdf(objs, pdf)
    GT["annot_render.pdf"] = {
        "rect": [200, 400, 400, 550],
        "raster": [208, 406, 248, 436],   # x0 y0 x1 y1 of the appearance's raster, page space
        "label": "StampInkVisible",
        "label_xy": [208, 520],
        "label_size": 12,
        "must_not_paint": ["HiddenStampMustNotPaint", "UnselectedStateOff", "NoStateSelected"],
        "must_paint": ["StampInkVisible", "SelectedStateOn"],
    }


def gen_no_spurious_figs():
    """Precision gate: a prose page with incidental tiny marks (a short underline rule, a
    small box) and NO figure caption anywhere. Weak vector candidates must NOT be promoted
    without an adjacent caption — the page must emit ZERO <figure> elements. Page 2 is a
    positive control (the same tiny diagram WITH a caption → exactly one figure), proving the
    gate discriminates rather than blanket-rejecting."""
