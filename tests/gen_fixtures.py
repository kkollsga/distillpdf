def gen_clipped_raster():
    """The same raster drawn three times: whole, clipped, and clipped under a ROTATED placement.

    ``vector::walk`` honours the active clip for path ink; ``img::walk`` tracked no clip at all,
    so a raster the content stream crops to a small window rendered at its FULL placement rect —
    and since rasters paint in true paint order, it covers whatever the page drew after it.

    Three geometrically identical 300x180 figures (stroked frame + 5 ticks = 6 paths, clearing
    ``MIN_PATHS``), 60 pt apart so they cluster separately, each holding one 160x120 pt raster at
    (140, y0+30). The 2x2 raster is red|green over blue|yellow, so which quarter survives is
    unambiguous — the clip takes the BOTTOM-LEFT quarter, which is blue.

      TOP    (y 560-740): unclipped — the control. Plain ``x/y/width/height``, no mask.
      MID    (y 320-500): ``140 350 80 60 re W n`` around an AXIS-ALIGNED placement. The window
                          is a pixel rectangle, so the SAMPLES are cropped and no mask is
                          emitted — the one answer that is also right for a plain ``<img>``.
      BOTTOM (y  80-260): the same clip around a ROTATED placement, where a page-space rectangle
                          is NOT a pixel rectangle. Those keep every pixel and an SVG
                          ``clip-path``, on a wrapping ``<g>`` (a ``clip-path`` on the
                          transformed ``<image>`` itself would be scaled by the placement matrix
                          and hide the raster outright)."""
    pdf = os.path.join(OUT, "clipped_raster.pdf")
    # 2x2: red | green over blue | yellow. Row 0 is the TOP row in PDF image space, so the
    # bottom-left quarter of the placement is BLUE.
    img = _flate_image(5, 2, 2, b"/DeviceRGB", 8,
                       bytes((220, 30, 40, 30, 160, 60, 40, 60, 210, 230, 190, 40)))

    def figure(y0, clip, rotated=False):
        frame = b"q 0 0 0 RG 1 w 72 %d 300 180 re S Q" % y0
        ticks = b"\n".join(
            b"q 0 0 0 RG 1 w %d %d m %d %d l S Q" % (72 + 20 * i, y0, 72 + 20 * i, y0 + 12)
            for i in range(1, 6)
        )
        # Both placements occupy x 140..300, y y0+30..y0+150; the second turns the pixels.
        cm = b"0 120 -160 0 300 %d" % (y0 + 30) if rotated else b"160 0 0 120 140 %d" % (y0 + 30)
        do = b"q %s cm /Im0 Do Q" % cm
        if clip:
            do = b"q 140 %d 80 60 re W n\n%s\nQ" % (y0 + 30, do)
        # A three-swatch legend down the left edge. Not decoration: the figure-ink gate
        # (`vector::passes_ink_gate`) demotes a cluster that draws neither a curve nor a
        # slanted line NOR a palette, and a black frame with black ticks is exactly the
        # shape of a ruled table. Every real composited figure in the corpus carries colour;
        # these swatches are what makes this minimal fixture one of them.
        legend = b"\n".join(
            b"q %s rg 78 %d 12 12 re f Q" % (rgb, y0 + 140 - 18 * i)
            for i, rgb in enumerate((b"0.85 0.20 0.15", b"0.20 0.55 0.80", b"0.95 0.75 0.10"))
        )
        return b"\n".join([frame, ticks, legend, do])

    stream = b"\n".join([
        b"BT /F1 12 Tf 72 760 Td (A clipped raster shows only its window.) Tj ET",
        figure(560, clip=False),
        figure(320, clip=True),
        figure(80, clip=True, rotated=True),
    ])
    objs = {
        1: b"<< /Type /Catalog /Pages 2 0 R >>",
        2: b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        3: (b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << "
            b"/Font << /F1 6 0 R >> /XObject << /Im0 5 0 R >> >> /Contents 4 0 R >>"),
        4: b"<< /Length %d >>\nstream\n%s\nendstream" % (len(stream), stream),
        5: img,
        6: b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    }
    _assemble_pdf(objs, pdf)
    GT["clipped_raster.pdf"] = {
        "figures": 3,
        "placement": [140, 350, 300, 470],   # x0 y0 x1 y1 of the axis-aligned clipped raster
        "clip": [140, 350, 220, 410],        # the window the page actually shows
        "window_rgb": [40, 60, 210],         # the bottom-left quarter is blue
    }


def gen_smask_group_raster():
    """The same raster drawn three times: whole, under an `/ExtGState /SMask` ALPHA group, and
    under a LUMINOSITY group whose non-black `/BC` makes its extent no bound at all.

    PDF 32000-1 §11.6.5.2 lets the graphics state carry a *soft mask*: the `/SMask /G` form is
    rendered off-screen and its alpha (or luminosity) multiplies everything painted while the
    state is in force. That is how a producer crops a render to a thumbnail window when the
    window is not a path clip — and the crate's `gs` handling read `/ca`/`/CA` only, so the
    raster painted at its full placement rect and covered the ink drawn after it.

    Geometry is `gen_clipped_raster`'s, deliberately: same three 300x180 figures, the same
    160x120 pt raster at (140, y0+30), the same 80x60 window — so the two fixtures pin the two
    mechanisms (path clip / soft mask) against an identical expected answer.

      TOP    (y 560-740): no `gs` — the control.
      MID    (y 320-500): `/GA gs`, whose group paints one opaque 80x60 rect at (140, 350).
                          The window is that rect; the placement is axis-aligned, so the
                          SAMPLES are cropped exactly as the path-clip case is.
      BOTTOM (y  80-260): `/GL gs`, a `/Luminosity` mask with `/BC [1]` — a WHITE backdrop,
                          which is opaque everywhere the group paints no ink. Its extent is
                          therefore not an upper bound on what shows, and the raster must come
                          back UNCROPPED. This is the regression that stops the approximation
                          from deleting content it cannot bound."""
    pdf = os.path.join(OUT, "smask_group_raster.pdf")
    # Same 2x2 as `gen_clipped_raster`: red | green over blue | yellow, so the bottom-left
    # quarter of the placement — the quarter the window keeps — is BLUE.
    img = _flate_image(5, 2, 2, b"/DeviceRGB", 8,
                       bytes((220, 30, 40, 30, 160, 60, 40, 60, 210, 230, 190, 40)))

    def mask_group(num, y0):
        body = b"q 0 0 0 rg 140 %d 80 60 re f Q" % (y0 + 30)
        return (b"<< /Type /XObject /Subtype /Form /BBox [0 0 612 792] "
                b"/Group << /Type /Group /S /Transparency /CS /DeviceGray >> /Length %d >>"
                b"\nstream\n%s\nendstream" % (len(body), body))

    def figure(y0, gs=None):
        frame = b"q 0 0 0 RG 1 w 72 %d 300 180 re S Q" % y0
        ticks = b"\n".join(
            b"q 0 0 0 RG 1 w %d %d m %d %d l S Q" % (72 + 20 * i, y0, 72 + 20 * i, y0 + 12)
            for i in range(1, 6)
        )
        # The `gs` runs BEFORE the `cm`: §11.6.5.2 evaluates the mask group under the CTM in
        # force at the `gs`, which here is page space — the group's rect is page coordinates.
        do = b"q %s160 0 0 120 140 %d cm /Im0 Do Q" % (b"/%s gs " % gs if gs else b"", y0 + 30)
        # See `gen_clipped_raster`: the figure-ink gate demotes a rects-only cluster with no
        # palette, so each figure carries the same three-swatch legend.
        legend = b"\n".join(
            b"q %s rg 78 %d 12 12 re f Q" % (rgb, y0 + 140 - 18 * i)
            for i, rgb in enumerate((b"0.85 0.20 0.15", b"0.20 0.55 0.80", b"0.95 0.75 0.10"))
        )
        return b"\n".join([frame, ticks, legend, do])

    stream = b"\n".join([
        b"BT /F1 12 Tf 72 760 Td (A soft-masked raster shows only its window.) Tj ET",
        figure(560),
        figure(320, gs=b"GA"),
        figure(80, gs=b"GL"),
    ])
    objs = {
        1: b"<< /Type /Catalog /Pages 2 0 R >>",
        2: b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        3: (b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << "
            b"/Font << /F1 6 0 R >> /XObject << /Im0 5 0 R >> /ExtGState << "
            b"/GA << /Type /ExtGState /SMask << /Type /Mask /G 7 0 R /S /Alpha >> >> "
            b"/GL << /Type /ExtGState /SMask << /Type /Mask /G 8 0 R /S /Luminosity /BC [1] >> >> "
            b">> >> /Contents 4 0 R >>"),
        4: b"<< /Length %d >>\nstream\n%s\nendstream" % (len(stream), stream),
        5: img,
        6: b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
        7: mask_group(7, 320),
        8: mask_group(8, 80),
    }
    _assemble_pdf(objs, pdf)
    GT["smask_group_raster.pdf"] = {
        "figures": 3,
        "placement": [140, 350, 300, 470],   # x0 y0 x1 y1 of the alpha-masked raster
        "window": [140, 350, 220, 410],      # what the alpha mask leaves visible
        "window_rgb": [40, 60, 210],         # the bottom-left quarter is blue
    }


def gen_smask_panel():
    """A JPEG cut-out over a coloured panel: the ``/SMask``'s transparency IS the figure.

    ``img.rs::rgba_uri`` composited the soft mask and then, whenever the source was
    ``DCTDecode``, flattened the RGBA onto **white** and re-encoded as JPEG — justified by
    "the HTML render background, so any edge/feather transparency looks identical". That
    premise holds for a raster laid on the page and fails inside a figure's ``<svg>``, where
    what sits behind the raster is the figure's own coloured panel: the flattening painted
    over it, and the panel vanished from the output.

    One 300x180 figure (stroked frame + 5 ticks + the panel = 7 paths, clearing
    ``MIN_PATHS``), painted panel-then-raster so the raster is on top, with a 160x120 pt
    ``DCTDecode`` raster wholly inside a teal panel. The mask is a hard split — the LEFT
    half fully opaque, the RIGHT half fully transparent — so the panel must show through
    exactly the right half and nothing about the assertion depends on feathering. (The mask
    is deliberately BINARY: the corpus case that surfaced this is a cut-out, not a soft
    edge, and a fix keyed on "is the mask soft" would leave it broken.)"""
    pdf = os.path.join(OUT, "smask_panel.pdf")
    buf = io.BytesIO()
    Image.new("RGB", (64, 64), (220, 30, 40)).save(buf, "JPEG", quality=95, subsampling=0)
    jpeg = buf.getvalue()
    # 64x64 gray mask: columns 0..31 opaque, 32..63 transparent.
    mask = bytes(255 if x < 32 else 0 for _ in range(64) for x in range(64))

    frame = b"q 0 0 0 RG 1 w 72 500 300 180 re S Q"
    ticks = b"\n".join(b"q 0 0 0 RG 1 w %d 500 m %d 512 l S Q" % (72 + 20 * i, 72 + 20 * i)
                       for i in range(1, 6))
    panel = b"q 0.2 0.6 0.6 rg 130 520 180 140 re f Q"
    raster = b"q 160 0 0 120 140 530 cm /Im0 Do Q"
    # A three-swatch legend down the left edge — see `gen_clipped_raster`: the figure-ink
    # gate demotes a rects-only cluster with no palette, and a lone teal panel is one colour.
    legend = b"\n".join(
        b"q %s rg 78 %d 12 12 re f Q" % (rgb, 640 - 18 * i)
        for i, rgb in enumerate((b"0.85 0.20 0.15", b"0.20 0.55 0.80", b"0.95 0.75 0.10"))
    )
    stream = b"\n".join([
        b"BT /F1 12 Tf 72 720 Td (A JPEG cut-out must not erase the panel behind it.) Tj ET",
        frame, ticks, legend, panel, raster,
    ])
    objs = {
        1: b"<< /Type /Catalog /Pages 2 0 R >>",
        2: b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        3: (b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << "
            b"/Font << /F1 7 0 R >> /XObject << /Im0 5 0 R >> >> /Contents 4 0 R >>"),
        4: b"<< /Length %d >>\nstream\n%s\nendstream" % (len(stream), stream),
        5: (b"<< /Type /XObject /Subtype /Image /Width 64 /Height 64 /ColorSpace /DeviceRGB "
            b"/BitsPerComponent 8 /Filter /DCTDecode /SMask 6 0 R /Length %d >>\nstream\n%s\nendstream"
            % (len(jpeg), jpeg)),
        6: _flate_image(6, 64, 64, b"/DeviceGray", 8, mask),
        7: b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    }
    _assemble_pdf(objs, pdf)
    GT["smask_panel.pdf"] = {
        "panel_fill": "#339999",
        "image_rgb": [220, 30, 40],
        # The composited <image> must be a lossless PNG carrying alpha, not an opaque JPEG.
        "expect_format": "png",
    }


def gen_cmyk_jpeg():
    """A DeviceCMYK JPEG — the one image kind whose bytes decode to a *silently wrong
    colour* rather than failing.

    PIL writes CMYK JPEGs the Adobe way (an APP14 marker, all four channels complemented),
    and reportlab passes the file straight through as ``DCTDecode`` with the matching
    ``/Decode [1 0 1 0 1 0 1 0]``. Any consumer that opens those bytes as a standalone
    JPEG applies the Adobe complement *and* never sees ``/Decode``, so it lands on the
    inverse of the authored colour: the white band reads as black.

    Three flat vertical bands with ``K=0``, so the authored CMYK maps to RGB identically
    under both the additive and the multiplicative conversion and the expected pixels are
    unambiguous. The ASCII85 layer reportlab adds also pins that the codec payload is
    unwrapped before the JPEG is read."""
    pdf = os.path.join(OUT, "cmyk_jpeg.pdf")
    jpg = os.path.join(OUT, "_cmyk.jpg")
    bands = [(0, 0, 0, 0), (255, 0, 0, 0), (0, 180, 0, 0)]  # white, cyan, magenta-ish
    im = Image.new("CMYK", (96, 48))
    px = im.load()
    for x in range(96):
        for y in range(48):
            px[x, y] = bands[min(x // 32, 2)]
    im.save(jpg, quality=95, subsampling=0)

    c = canvas.Canvas(pdf, pagesize=letter)
    title(c, "DeviceCMYK JPEG")
    y = PAGE_H - 130
    y = para(c, "The three flat bands below are a CMYK JPEG with an Adobe marker: white, "
                "cyan, and magenta. Read as a standalone JPEG they invert.", y)
    draw_image(c, jpg, LM, y - 100, width=192, height=96)
    y -= 116
    c.setFont("Helvetica", 9.5)
    c.drawString(LM, y, "Figure 1: Three flat CMYK bands.")
    c.showPage()
    c.save()
    os.remove(jpg)
