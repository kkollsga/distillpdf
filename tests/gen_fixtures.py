def gen_clipped_raster():
    """The same raster drawn twice — once whole, once under a ``re W n`` clip.

    ``vector::walk`` honours the active clip for path ink (it stores it and emits an SVG
    ``<clipPath>``); ``img::walk`` tracked no clip at all, so a raster the content stream
    crops to a small window rendered at its FULL placement rect. Since rasters paint in true
    paint order that means covering whatever the page drew after it.

    Two geometrically identical 300x180 figures (stroked frame + 5 ticks = 6 paths, clearing
    ``MIN_PATHS``), 220 pt apart so they cluster separately, each holding one 160x120 pt
    raster at (140, y0+30):

      TOP    (y 520-700): unclipped — the control. Plain ``x/y/width/height`` ``<image>``,
                          no ``clip-path``.
      BOTTOM (y 120-300): the identical ``Do`` under ``140 150 80 60 re W n``, i.e. the
                          raster's BOTTOM-LEFT QUARTER. The ``<image>`` must carry a
                          ``clip-path``, must be placed by MATRIX (the pixels still fill the
                          whole 160x120 rect — only the window shrank), and the figure's
                          recorded extent must be the 80x60 crop, not the 160x120 placement.

    The raster is four flat quadrant colours, so which quarter survives is unambiguous."""
    pdf = os.path.join(OUT, "clipped_raster.pdf")
    # 2x2: red | green over blue | yellow. In PDF image space row 0 is the TOP row, so the
    # bottom-left quarter of the placement is BLUE.
    img = _flate_image(5, 2, 2, b"/DeviceRGB", 8,
                       bytes((220, 30, 40, 30, 160, 60, 40, 60, 210, 230, 190, 40)))

    def figure(y0, clip):
        frame = b"q 0 0 0 RG 1 w 72 %d 300 180 re S Q" % y0
        ticks = b"\n".join(
            b"q 0 0 0 RG 1 w %d %d m %d %d l S Q" % (72 + 20 * i, y0, 72 + 20 * i, y0 + 12)
            for i in range(1, 6)
        )
        do = b"q 160 0 0 120 140 %d cm /Im0 Do Q" % (y0 + 30)
        if clip:
            do = b"q 140 %d 80 60 re W n\n%s\nQ" % (y0 + 30, do)
        return b"\n".join([frame, ticks, do])

    stream = b"\n".join([
        b"BT /F1 12 Tf 72 720 Td (A clipped raster shows only its window.) Tj ET",
        figure(520, clip=False),
        figure(120, clip=True),
    ])
    objs = {
        1: b"<< /Type /Catalog /Pages 2 0 R >>",
        2: b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        3: (b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << "
            b"/Font << /F1 6 0 R >> /XObject << /Im0 5 0 R >> >> /Contents 4 0 R >>"),
        4: b"<< /Length %d >>\nstream\n%s\nendstream" % (len(stream), stream),
        5: img,
        6: b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    }
    _assemble_pdf(objs, pdf)
    GT["clipped_raster.pdf"] = {
        "figures": 2,
        "placement": [140, 150, 300, 270],   # x0 y0 x1 y1 of the clipped figure's raster
        "clip": [140, 150, 220, 210],        # the window the page actually shows
    }


def gen_smask_panel():
    """A JPEG cut-out over a coloured panel: the ``/SMask``'s transparency IS the figure.

    ``img.rs::rgba_uri`` composited the soft mask and then, whenever the source was
    ``DCTDecode``, flattened the RGBA onto **white** and re-encoded as JPEG — justified by
    "the HTML render background, so any edge/feather transparency looks identical". That
    premise holds for a raster laid on the page and fails inside a figure's ``<svg>``, where
    what sits behind the raster is the figure's own coloured panel: the flattening painted
    over it, and the panel vanished from the output.

    One 300x180 figure (stroked frame + 5 ticks + the panel = 7 paths, clearing
    ``MIN_PATHS``), painted panel-then-raster so the raster is on top, with a 160x120 pt
    ``DCTDecode`` raster wholly inside a teal panel. The mask is a hard split — the LEFT
    half fully opaque, the RIGHT half fully transparent — so the panel must show through
    exactly the right half and nothing about the assertion depends on feathering. (The mask
    is deliberately BINARY: the corpus case that surfaced this is a cut-out, not a soft
    edge, and a fix keyed on "is the mask soft" would leave it broken.)"""
    pdf = os.path.join(OUT, "smask_panel.pdf")
    buf = io.BytesIO()
    Image.new("RGB", (64, 64), (220, 30, 40)).save(buf, "JPEG", quality=95, subsampling=0)
    jpeg = buf.getvalue()
    # 64x64 gray mask: columns 0..31 opaque, 32..63 transparent.
    mask = bytes(255 if x < 32 else 0 for _ in range(64) for x in range(64))

    frame = b"q 0 0 0 RG 1 w 72 500 300 180 re S Q"
    ticks = b"\n".join(b"q 0 0 0 RG 1 w %d 500 m %d 512 l S Q" % (72 + 20 * i, 72 + 20 * i)
                       for i in range(1, 6))
    panel = b"q 0.2 0.6 0.6 rg 130 520 180 140 re f Q"
    raster = b"q 160 0 0 120 140 530 cm /Im0 Do Q"
    stream = b"\n".join([
        b"BT /F1 12 Tf 72 720 Td (A JPEG cut-out must not erase the panel behind it.) Tj ET",
        frame, ticks, panel, raster,
    ])
    objs = {
        1: b"<< /Type /Catalog /Pages 2 0 R >>",
        2: b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        3: (b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << "
            b"/Font << /F1 7 0 R >> /XObject << /Im0 5 0 R >> >> /Contents 4 0 R >>"),
        4: b"<< /Length %d >>\nstream\n%s\nendstream" % (len(stream), stream),
        5: (b"<< /Type /XObject /Subtype /Image /Width 64 /Height 64 /ColorSpace /DeviceRGB "
            b"/BitsPerComponent 8 /Filter /DCTDecode /SMask 6 0 R /Length %d >>\nstream\n%s\nendstream"
            % (len(jpeg), jpeg)),
        6: _flate_image(6, 64, 64, b"/DeviceGray", 8, mask),
        7: b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    }
    _assemble_pdf(objs, pdf)
    GT["smask_panel.pdf"] = {
        "panel_fill": "#339999",
        "image_rgb": [220, 30, 40],
        # The composited <image> must be a lossless PNG carrying alpha, not an opaque JPEG.
        "expect_format": "png",
    }


def gen_cmyk_jpeg():
    """A DeviceCMYK JPEG — the one image kind whose bytes decode to a *silently wrong
    colour* rather than failing.

    PIL writes CMYK JPEGs the Adobe way (an APP14 marker, all four channels complemented),
    and reportlab passes the file straight through as ``DCTDecode`` with the matching
    ``/Decode [1 0 1 0 1 0 1 0]``. Any consumer that opens those bytes as a standalone
    JPEG applies the Adobe complement *and* never sees ``/Decode``, so it lands on the
    inverse of the authored colour: the white band reads as black.

    Three flat vertical bands with ``K=0``, so the authored CMYK maps to RGB identically
    under both the additive and the multiplicative conversion and the expected pixels are
    unambiguous. The ASCII85 layer reportlab adds also pins that the codec payload is
    unwrapped before the JPEG is read."""
    pdf = os.path.join(OUT, "cmyk_jpeg.pdf")
    jpg = os.path.join(OUT, "_cmyk.jpg")
    bands = [(0, 0, 0, 0), (255, 0, 0, 0), (0, 180, 0, 0)]  # white, cyan, magenta-ish
    im = Image.new("CMYK", (96, 48))
    px = im.load()
    for x in range(96):
        for y in range(48):
            px[x, y] = bands[min(x // 32, 2)]
    im.save(jpg, quality=95, subsampling=0)

    c = canvas.Canvas(pdf, pagesize=letter)
    title(c, "DeviceCMYK JPEG")
    y = PAGE_H - 130
    y = para(c, "The three flat bands below are a CMYK JPEG with an Adobe marker: white, "
                "cyan, and magenta. Read as a standalone JPEG they invert.", y)
    c.drawImage(jpg, LM, y - 100, width=192, height=96)
    y -= 116
    c.setFont("Helvetica", 9.5)
    c.drawString(LM, y, "Figure 1: Three flat CMYK bands.")
    c.showPage()
    c.save()
    os.remove(jpg)
    GT["cmyk_jpeg.pdf"] = {
        "caption": "Figure 1: Three flat CMYK bands.",
        # sampled at each band's centre; K=0 so RGB = 255 - ink
        "bands_rgb": [[255, 255, 255], [0, 255, 255], [255, 75, 255]],
        "sample_x": [15, 47, 79],
        "sample_y": 24,
        "width": 96,
        "height": 48,
    }


