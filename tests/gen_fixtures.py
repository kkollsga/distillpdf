def gen_form_image():
    """Raster images that live inside a Form XObject — the shape every LaTeX/e-filing
    producer emits, and the one lopdf's non-recursive ``get_page_images()`` is blind to
    (13 of 54 corpus documents reported *no* images at all).

    Page 1 is the clean case: the page's own ``/XObject`` holds only the form, and the
    single image XObject lives in the FORM's ``/Resources``. ``extract_images()`` must
    return exactly one row for it. (This page is also the render-path seed: one captioned
    figure, one placed raster.)

    Page 2 pins the ordering contract: a raster drawn DIRECTLY on the page, then a second
    one nested in a form. The direct image must keep index 0 — the index it had before the
    resource walk existed — and the form-nested one is appended at index 1."""
    pdf = os.path.join(OUT, "form_image.pdf")
    png_a = os.path.join(OUT, "_form_a.png")
    png_b = os.path.join(OUT, "_form_b.png")
    # Two distinguishable sizes so a test can tell the nested row from the direct one.
    for path, (w, h), fill in ((png_a, (240, 160), (60, 110, 200)), (png_b, (120, 90), (200, 90, 70))):
        im = Image.new("RGB", (w, h), "white")
        d = ImageDraw.Draw(im)
        d.rectangle([4, 4, w - 5, h - 5], outline="black", width=2)
        d.rectangle([w // 4, h // 3, w * 3 // 4, h - 12], fill=fill)
        im.save(path)

    c = canvas.Canvas(pdf, pagesize=letter)
    # --- page 1: the ONLY image is inside a form ---------------------------------
    title(c, "Form XObject Raster")
    y = PAGE_H - 120
    y = para(c, "The bar chart in Figure 1 is drawn inside a form XObject, so it is reachable "
                "only through the form's own resource dictionary.", y)
    c.beginForm("rasterform")
    c.drawImage(png_a, LM, y - 150, width=240, height=150)
    c.endForm()
    c.doForm("rasterform")
    y -= 164
    c.setFont("Helvetica", 9.5)
    c.drawString(LM, y, "Figure 1: A raster bar chart drawn inside a form XObject.")
    c.showPage()
    # --- page 2: direct image first, then a form-nested one ----------------------
    y = PAGE_H - 100
    c.drawImage(png_b, LM, y - 90, width=120, height=90)   # direct -> index 0
    c.beginForm("nestedform")
    c.drawImage(png_a, LM + 200, y - 150, width=240, height=150)  # nested -> index 1
    c.endForm()
    c.doForm("nestedform")
    c.showPage()
    c.save()
    os.remove(png_a)
    os.remove(png_b)
    GT["form_image.pdf"] = {
        "caption": "Figure 1: A raster bar chart drawn inside a form XObject.",
        "page1_images": [{"width": 240, "height": 160}],
        # page 2: the DIRECT image keeps index 0, the form-nested one is appended.
        "page2_images": [{"index": 0, "width": 120, "height": 90},
                         {"index": 1, "width": 240, "height": 160}],
    }


def _raw_rgb_image(w, h):
    """An uncompressed DeviceRGB image XObject of the given pixel size (hand-written: no
    filter, so the fixture stays byte-inspectable and needs no codec)."""
    px = bytes(0x20 + ((i * 7) % 0x5F) for i in range(w * h * 3))
    return (b"<< /Type /XObject /Subtype /Image /Width %d /Height %d /ColorSpace /DeviceRGB "
            b"/BitsPerComponent 8 /Length %d >>\nstream\n%s\nendstream" % (w, h, len(px), px))


def gen_undrawn_image():
    """Images listed in a page's ``/Resources`` but NEVER drawn by its content stream.

    One ``/Resources`` dictionary is shared by both pages via the ``/Pages`` node — the
    iText layout a 166-page corpus preprint uses, where every page's resource dict lists
    every page-body form in the document. A pure reachability walk therefore makes each
    page reach every image in the file (56,108 rows for 338 distinct images on that
    document). A page's images are the ones it actually PAINTS, so:

      page 1 draws ``/ImDrawn`` directly → only that row, never ``/ImNever``;
      page 2 draws only the form ``/TPL``, whose own content paints ``/ImInForm`` and
      leaves ``/ImFormNever`` untouched → exactly one row, the nested one.

    reportlab always draws what it embeds, so this is hand-assembled."""
    pdf = os.path.join(OUT, "undrawn_image.pdf")
    page1_content = b"q 200 0 0 150 72 500 cm /ImDrawn Do Q"
    page2_content = b"q 1 0 0 1 0 0 cm /TPL Do Q"
    form_content = b"q 180 0 0 120 72 300 cm /ImInForm Do Q"
    objs = {
        1: b"<< /Type /Catalog /Pages 2 0 R >>",
        # The shared, INHERITED resource dictionary: both pages reach all four images.
        2: (b"<< /Type /Pages /Kids [3 0 R 4 0 R] /Count 2 /MediaBox [0 0 612 792] "
            b"/Resources 5 0 R >>"),
        3: b"<< /Type /Page /Parent 2 0 R /Contents 6 0 R >>",
        4: b"<< /Type /Page /Parent 2 0 R /Contents 7 0 R >>",
        5: (b"<< /XObject << /ImDrawn 8 0 R /ImNever 9 0 R /TPL 10 0 R >> >>"),
        6: b"<< /Length %d >>\nstream\n%s\nendstream" % (len(page1_content), page1_content),
        7: b"<< /Length %d >>\nstream\n%s\nendstream" % (len(page2_content), page2_content),
        8: _raw_rgb_image(40, 30),   # drawn on page 1
        9: _raw_rgb_image(41, 31),   # listed everywhere, painted nowhere
        10: (b"<< /Type /XObject /Subtype /Form /FormType 1 /BBox [0 0 612 792] "
             b"/Resources << /XObject << /ImInForm 11 0 R /ImFormNever 12 0 R >> >> "
             b"/Length %d >>\nstream\n%s\nendstream" % (len(form_content), form_content)),
        11: _raw_rgb_image(42, 32),  # drawn by the form
        12: _raw_rgb_image(43, 33),  # in the form's resources, never painted
    }
    _assemble_pdf(objs, pdf)
    GT["undrawn_image.pdf"] = {
        "page1_images": [{"index": 0, "width": 40, "height": 30}],
        "page2_images": [{"index": 0, "width": 42, "height": 32}],
        "never_drawn": [{"width": 41, "height": 31}, {"width": 43, "height": 33}],
    }


def _flate_image(num, w, h, cs, bpc, samples, extra=b""):
    """A FlateDecode image XObject: the shape almost every non-photographic PDF raster has,
    and the one ``extract_images()`` used to hand back as compressed samples with no
    container (``format='raw'``, unopenable)."""
    data = zlib.compress(samples)
    return (b"<< /Type /XObject /Subtype /Image /Width %d /Height %d /ColorSpace %s "
            b"/BitsPerComponent %d /Filter /FlateDecode %s/Length %d >>\nstream\n%s\nendstream"
            % (w, h, cs, bpc, extra, len(data), data))


def gen_colorspace_images():
    """Flate-compressed rasters in the colour spaces that made ``color_space`` come back
    ``None`` — and whose samples had no container at all.

    Four images, each pinning one resolution step the reporter used to skip:

      ``/ImIndexed``  ``[/Indexed /DeviceRGB 3 <palette>]`` at 4 bits per component —
                      packed sub-byte samples plus a palette lookup;
      ``/ImIcc``      ``/ColorSpace`` written as an **indirect reference** to an
                      ``[/ICCBased …]`` array whose stream ``/N`` is the only statement of
                      the component count (the exact shape of the corpus preprint image
                      that reported ``None``);
      ``/ImCmyk``     ``/DeviceCMYK`` samples, which need the CMYK→RGB reduction;
      ``/ImNamedCs``  ``/ColorSpace /CS0``, a **name defined in the page's ``/Resources``
                      ``/ColorSpace`` sub-dictionary** — meaningless without that lookup.

    reportlab flattens every image it embeds to DeviceRGB/DeviceGray, so this is
    hand-assembled; that also lets the pixel values be exact, which is what the tests
    assert on the assembled PNGs."""
    pdf = os.path.join(OUT, "colorspace_images.pdf")
    # --- /ImIndexed: 4x2 @ 4bpc, palette red/green/blue/white -------------------
    palette = bytes((255, 0, 0, 0, 255, 0, 0, 0, 255, 255, 255, 255))
    idx_samples = bytes((0x01, 0x23, 0x32, 0x10))  # row0: 0 1 2 3 · row1: 3 2 1 0
